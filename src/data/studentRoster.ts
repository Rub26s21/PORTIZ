/**
 * Returns the official student record for a register number, if present.
 */
export function getStudentByRegisterNo(regNo: string | null | undefined): RosterStudent | null {
  if (!regNo) return null;
  const clean = String(regNo).trim().toUpperCase();
  return OFFICIAL_STUDENT_ROSTER[clean] || null;
}

/**
 * Checks if a register number strictly matches the provided section.
 */
export function validateStudentSection(regNo: string | null | undefined, section: string | null | undefined): {
  isValid: boolean;
  officialSection: 'A' | 'B' | 'C' | 'D' | null;
  studentName: string | null;
  error?: string;
} {
  if (!regNo) {
    return { isValid: false, officialSection: null, studentName: null, error: 'Register number is required' };
  }
  const clean = String(regNo).trim().toUpperCase();
  const student = OFFICIAL_STUDENT_ROSTER[clean] || null;
  if (!student) {
    return { isValid: true, officialSection: null, studentName: null };
  }
  const cleanSection = String(section || '').trim().toUpperCase().replace('SECTION', '').trim();
  if (student.section !== cleanSection) {
    return {
      isValid: false,
      officialSection: student.section,
      studentName: student.name,
      error: 'Register number ' + student.regNo + ' is assigned to Section ' + student.section + ', but Section ' + (cleanSection || 'None') + ' was selected. You cannot take the test in another section.',
    };
  }
  return {
    isValid: true,
    officialSection: student.section,
    studentName: student.name,
  };
}
